-- * NÃO habilita Anonymous Sign-In.
-- * NÃO altera permissões, tabelas, funções ou policies do schema public.
-- * A criança usa um segredo aleatório local; apenas o SHA-256 é salvo no banco.
-- * Navegadores não recebem acesso direto às tabelas. Toda escrita/leitura passa
