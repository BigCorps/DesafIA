create or replace function desafia.real_user()
returns boolean language sql stable
set search_path=desafia,pg_catalog,extensions,pg_temp as $$
  select auth.uid() is not null
     and not coalesce((auth.jwt()->>'is_anonymous')::boolean,false)
$$;

create or replace function desafia.is_family_parent(fid uuid)
returns boolean language sql stable security definer
set search_path=desafia,pg_catalog,extensions,pg_temp as $$
  select desafia.real_user() and exists (
    select 1 from desafia.family_members m
    where m.family_id=fid and m.user_id=auth.uid()
  )
$$;

create or replace function desafia.family_is_plus(fid uuid)
returns boolean language sql stable security definer
set search_path=desafia,pg_catalog,extensions,pg_temp as $$
  select exists (
    select 1 from desafia.families f
    where f.id=fid and f.plan='plus'
      and (f.plan_expires_at is null or f.plan_expires_at>now())
  )
$$;

create or replace function desafia.family_today(fid uuid)
returns date language sql stable security definer
set search_path=desafia,pg_catalog,extensions,pg_temp as $$
  select (now() at time zone coalesce((select timezone from desafia.families where id=fid),'America/Sao_Paulo'))::date
$$;

create or replace function desafia.family_week_start(fid uuid)
returns date language sql stable security definer
set search_path=desafia,pg_catalog,extensions,pg_temp as $$
  select date_trunc('week',desafia.family_today(fid)::timestamp)::date
$$;

create or replace function desafia.clean_code(raw text)
returns text language sql immutable
set search_path=desafia,pg_catalog,extensions,pg_temp as $$
  select upper(regexp_replace(coalesce(raw,''),'[^A-Za-z0-9]','','g'))
$$;

create or replace function desafia.new_code()
returns text language plpgsql volatile security definer
set search_path=desafia,pg_catalog,extensions,pg_temp as $$
declare
  alphabet constant text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  raw bytea := extensions.gen_random_bytes(8);
  result text := '';
  i int;
begin
  for i in 0..7 loop
    result := result || substr(alphabet,(get_byte(raw,i) % length(alphabet))+1,1);
  end loop;
  return result;
end $$;

create or replace function desafia.token_hash(p_token text)
returns bytea language plpgsql immutable security definer
set search_path=desafia,pg_catalog,extensions,pg_temp as $$
begin
  if p_token is null or p_token !~ '^[A-Za-z0-9_-]{40,80}$' then
    raise exception 'INVALID_DEVICE_TOKEN';
  end if;
  return extensions.digest(p_token,'sha256');
end $$;

create or replace function desafia.device_player(p_token text)
returns uuid language sql stable security definer
set search_path=desafia,pg_catalog,extensions,pg_temp as $$
  select d.player_id from desafia.devices d
  where d.token_hash=desafia.token_hash(p_token) and d.revoked_at is null
$$;

create or replace function desafia.player_week_points(pid uuid, since_day date)
returns integer language sql stable security definer
set search_path=desafia,pg_catalog,extensions,pg_temp as $$
  select (
    coalesce((select sum(l.star_reward) from desafia.mission_logs l
      where l.player_id=pid and l.status='done' and l.day>=since_day),0)
    + coalesce((select sum(d.star_bonus) from desafia.daily_completions d
      where d.player_id=pid and d.day>=since_day),0)
  )::int
$$;

create or replace function desafia.family_week_points(fid uuid)
returns integer language sql stable security definer
set search_path=desafia,pg_catalog,extensions,pg_temp as $$
  select coalesce(sum(desafia.player_week_points(p.id,desafia.family_week_start(fid))),0)::int
  from desafia.players p where p.family_id=fid
$$;

create or replace function desafia.player_streak(pid uuid, fid uuid)
returns integer language sql stable security definer
set search_path=desafia,pg_catalog,extensions,pg_temp as $$
  with recursive latest as (
    select max(day) as day from desafia.daily_completions
    where player_id=pid and day>=desafia.family_today(fid)-1
  ), streak(day,n) as (
    select day,1 from latest where day is not null
    union all
    select d.day,s.n+1
    from streak s join desafia.daily_completions d
      on d.player_id=pid and d.day=s.day-1
  )
  select coalesce(max(n),0)::int from streak
$$;

create or replace function desafia.challenge_progress(cid uuid, pid uuid)
returns integer language sql stable security definer
set search_path=desafia,pg_catalog,extensions,pg_temp as $$
