    into lvl from desafia.players where id=pid;
  hat:=case p_look->>'hat' when 'bone' then case when lvl>=2 then 'bone' else 'none' end when 'festa' then case when lvl>=3 then 'festa' else 'none' end when 'gorro' then case when lvl>=4 then 'gorro' else 'none' end when 'coroa' then case when lvl>=6 then 'coroa' else 'none' end when 'mago' then case when lvl>=9 then 'mago' else 'none' end else 'none' end;
  acc:=case p_look->>'acc' when 'oculos' then case when lvl>=2 then 'oculos' else 'none' end when 'laco' then case when lvl>=3 then 'laco' else 'none' end when 'gravata' then case when lvl>=5 then 'gravata' else 'none' end else 'none' end;
  clean:=jsonb_build_object('color',case when p_look->>'color' in('rosa','azul','verde','amarelo','lilas') then p_look->>'color' else 'rosa' end,'hat',hat,'acc',acc);
  update desafia.players set pet_name=coalesce(nullif(left(trim(p_pet_name),12),''),pet_name),look=clean where id=pid;
  update desafia.devices set last_seen_at=now() where token_hash=desafia.token_hash(p_device_token);
end $$;

create or replace function desafia.kid_snapshot(p_device_token text)
returns jsonb language plpgsql security definer
set search_path=desafia,pg_catalog,extensions,pg_temp as $$
declare pid uuid;fid uuid;today date;ws date;
begin
  if auth.uid() is not null then raise exception 'FORBIDDEN'; end if;
  pid:=desafia.device_player(p_device_token);if pid is null then return null; end if;
  select family_id into fid from desafia.players where id=pid;today:=desafia.family_today(fid);ws:=desafia.family_week_start(fid);
  update desafia.devices set last_seen_at=now() where token_hash=desafia.token_hash(p_device_token);
  return jsonb_build_object(
    'family',(select jsonb_build_object('name',f.name) from desafia.families f where f.id=fid),
    'family_goal',jsonb_build_object('current',desafia.family_week_points(fid),'target',(select weekly_goal from desafia.families where id=fid)),
    'player',(select jsonb_build_object('id',p.id,'nickname',p.nickname,'avatar',p.avatar,'pet_name',p.pet_name,'look',p.look,'xp',p.xp,'wallet',p.wallet,'week_points',desafia.player_week_points(p.id,ws),'streak',desafia.player_streak(p.id,fid),'daily_bonus_day',(select max(day) from desafia.daily_completions where player_id=p.id and day=today)) from desafia.players p where p.id=pid),
    'missions',coalesce((select jsonb_agg(jsonb_build_object('id',m.id,'title',m.title,'icon',m.icon,'star_reward',m.star_reward,'xp_reward',m.xp_reward,'time_of_day',m.time_of_day,'status',coalesce(l.status,'todo')) order by m.sort,m.created_at) from desafia.missions m left join desafia.mission_logs l on l.mission_id=m.id and l.player_id=pid and l.day=today where m.family_id=fid and m.active and m.audience='child'),'[]'::jsonb),
    'rewards',coalesce((select jsonb_agg(jsonb_build_object('id',r.id,'title',r.title,'icon',r.icon,'cost',r.cost,'pending',exists(select 1 from desafia.reward_requests q where q.reward_id=r.id and q.player_id=pid and q.status='pending')) order by r.cost) from desafia.rewards r where r.family_id=fid and r.active),'[]'::jsonb),
    'recent_rewards',coalesce((select jsonb_agg(jsonb_build_object('id',q.id,'status',q.status,'title',r.title,'icon',r.icon,'decided_at',q.decided_at) order by q.decided_at) from desafia.reward_requests q join desafia.rewards r on r.id=q.reward_id where q.player_id=pid and q.status<>'pending' and q.decided_at>now()-interval '2 days'),'[]'::jsonb),
    'ranking',coalesce((select jsonb_agg(jsonb_build_object('nickname',p.nickname,'avatar',p.avatar,'kind',p.kind,'points',desafia.player_week_points(p.id,ws),'me',p.id=pid) order by desafia.player_week_points(p.id,ws) desc) from desafia.players p where p.family_id=fid),'[]'::jsonb),
    'challenges',coalesce((select jsonb_agg(jsonb_build_object('title',c.title,'target_days',c.target_days,'prize',c.prize,'icon',m.icon,'done',desafia.challenge_progress(c.id,pid),'ends_on',c.ends_on)) from desafia.challenges c join desafia.missions m on m.id=c.mission_id where c.family_id=fid and (c.player_id is null or c.player_id=pid) and today between c.starts_on and c.ends_on),'[]'::jsonb),
    'leagues',coalesce((select jsonb_agg(desafia.league_scores(lf.league_id,fid)) from desafia.league_families lf where lf.family_id=fid),'[]'::jsonb)
  );
end $$;

