create or replace function desafia.my_families()
returns jsonb language plpgsql stable security definer
set search_path=desafia,pg_catalog,extensions,pg_temp as $$
begin
  if not desafia.real_user() then raise exception 'LOGIN_REQUIRED'; end if;
  return coalesce((select jsonb_agg(jsonb_build_object(
    'id',f.id,'name',f.name,'role',m.role,'created_at',f.created_at
  ) order by f.created_at)
  from desafia.family_members m join desafia.families f on f.id=m.family_id
  where m.user_id=auth.uid()),'[]'::jsonb);
end $$;

create or replace function desafia.create_family(p_name text,p_display_name text,p_avatar text default '🦊')
returns uuid language plpgsql security definer
set search_path=desafia,pg_catalog,extensions,pg_temp as $$
declare fid uuid;
begin
  if not desafia.real_user() then raise exception 'LOGIN_REQUIRED'; end if;
  if char_length(trim(p_name)) not between 1 and 60 then raise exception 'INVALID_NAME'; end if;
  insert into desafia.families(name) values(trim(p_name)) returning id into fid;
  insert into desafia.family_members(family_id,user_id,role,display_name)
    values(fid,auth.uid(),'owner',left(coalesce(nullif(trim(p_display_name),''),'Responsável'),30));
  insert into desafia.players(family_id,kind,user_id,nickname,avatar)
    values(fid,'adult',auth.uid(),left(coalesce(nullif(trim(p_display_name),''),'Responsável'),30),coalesce(nullif(p_avatar,''),'🦊'));
  perform desafia.seed_family(fid);
  return fid;
end $$;

create or replace function desafia.update_family(p_family uuid,p_name text,p_weekly_goal integer)
returns void language plpgsql security definer
set search_path=desafia,pg_catalog,extensions,pg_temp as $$
begin
  if not desafia.is_family_parent(p_family) then raise exception 'FORBIDDEN'; end if;
  update desafia.families set
    name=left(coalesce(nullif(trim(p_name),''),name),60),
    weekly_goal=greatest(100,least(10000,coalesce(p_weekly_goal,weekly_goal)))
  where id=p_family;
end $$;

create or replace function desafia.create_child(p_family uuid,p_nickname text,p_avatar text default '🌸')
returns uuid language plpgsql security definer
set search_path=desafia,pg_catalog,extensions,pg_temp as $$
declare pid uuid;n int;
begin
  if not desafia.is_family_parent(p_family) then raise exception 'FORBIDDEN'; end if;
  perform 1 from desafia.families where id=p_family for update;
  select count(*) into n from desafia.players where family_id=p_family and kind='child';
  if n>=1 and not desafia.family_is_plus(p_family) then raise exception 'PLUS_REQUIRED'; end if;
  if n>=10 then raise exception 'LIMIT_REACHED'; end if;
  insert into desafia.players(family_id,kind,nickname,avatar)
    values(p_family,'child',left(trim(p_nickname),30),coalesce(nullif(p_avatar,''),'🌸')) returning id into pid;
  return pid;
end $$;

