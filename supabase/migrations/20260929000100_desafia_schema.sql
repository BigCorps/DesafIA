create or replace function desafia.create_pairing_code(p_player uuid)
returns jsonb language plpgsql security definer
set search_path=desafia,pg_catalog,extensions,pg_temp as $$
declare fid uuid;c text;exp timestamptz:=now()+interval '30 minutes';
begin
  select family_id into fid from desafia.players where id=p_player and kind='child';
  if fid is null or not desafia.is_family_parent(fid) then raise exception 'FORBIDDEN'; end if;
  delete from desafia.pairing_codes where player_id=p_player or expires_at<now();
  loop
    c:=desafia.new_code();
    begin
      insert into desafia.pairing_codes(code,player_id,expires_at) values(c,p_player,exp);exit;
    exception when unique_violation then null;
    end;
  end loop;
  return jsonb_build_object('code',c,'expires_at',exp);
end $$;

create or replace function desafia.parent_revoke_device(p_family uuid,p_device uuid)
returns void language plpgsql security definer
set search_path=desafia,pg_catalog,extensions,pg_temp as $$
begin
  if not desafia.is_family_parent(p_family) then raise exception 'FORBIDDEN'; end if;
  update desafia.devices d set revoked_at=now()
  from desafia.players p where d.id=p_device and d.player_id=p.id and p.family_id=p_family;
end $$;

create or replace function desafia.create_parent_invite(p_family uuid)
returns jsonb language plpgsql security definer
set search_path=desafia,pg_catalog,extensions,pg_temp as $$
declare c text;exp timestamptz:=now()+interval '2 days';
begin
  if not desafia.is_family_parent(p_family) then raise exception 'FORBIDDEN'; end if;
  delete from desafia.parent_invites where expires_at<now();
  loop
    c:=desafia.new_code();
    begin
      insert into desafia.parent_invites(code,family_id,expires_at,created_by)
        values(c,p_family,exp,auth.uid());
      exit;
    exception when unique_violation then
      null;
    end;
  end loop;
  return jsonb_build_object('code',c,'expires_at',exp);
end $$;

create or replace function desafia.accept_parent_invite(p_code text,p_display_name text,p_avatar text default '🐻')
returns uuid language plpgsql security definer
set search_path=desafia,pg_catalog,extensions,pg_temp as $$
declare fid uuid;
begin
  if not desafia.real_user() then raise exception 'LOGIN_REQUIRED'; end if;
  select family_id into fid from desafia.parent_invites where code=desafia.clean_code(p_code) and expires_at>now() for update;
  if fid is null then raise exception 'INVALID_CODE'; end if;
  insert into desafia.family_members(family_id,user_id,role,display_name)
    values(fid,auth.uid(),'parent',left(trim(p_display_name),30)) on conflict(family_id,user_id) do nothing;
  insert into desafia.players(family_id,kind,user_id,nickname,avatar)
    values(fid,'adult',auth.uid(),left(trim(p_display_name),30),coalesce(nullif(p_avatar,''),'🐻')) on conflict(family_id,user_id) do nothing;
  delete from desafia.parent_invites where code=desafia.clean_code(p_code);
  return fid;
end $$;

create or replace function desafia.decide_mission(p_log uuid,p_approve boolean)
returns void language plpgsql security definer
set search_path=desafia,pg_catalog,extensions,pg_temp as $$
