create or replace function desafia.maybe_award_daily_bonus(pid uuid)
returns boolean language plpgsql security definer
set search_path=desafia,pg_catalog,extensions,pg_temp as $$
declare
  p desafia.players;
  today date;
  expected_count int;
  done_count int;
  inserted_count int;
begin
  select * into p from desafia.players where id=pid;
  if p.id is null or p.kind<>'child' then return false; end if;
  today:=desafia.family_today(p.family_id);
  select count(*) into expected_count from desafia.missions m
    where m.family_id=p.family_id and m.audience='child' and m.active;
  if expected_count=0 then return false; end if;
  select count(*) into done_count from desafia.mission_logs l
    join desafia.missions m on m.id=l.mission_id
    where l.player_id=pid and l.day=today and l.status='done'
      and m.family_id=p.family_id and m.audience='child' and m.active;
  if done_count<expected_count then return false; end if;
  insert into desafia.daily_completions(player_id,day,star_bonus,xp_bonus)
    values(pid,today,25,15) on conflict do nothing;
  get diagnostics inserted_count=row_count;
  if inserted_count>0 then
    update desafia.players set wallet=wallet+25,xp=xp+15 where id=pid;
    return true;
  end if;
  return false;
end $$;

